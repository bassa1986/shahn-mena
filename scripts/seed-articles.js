async function seedArticles() {
  console.log('Seeding 10 articles...')
  for (const article of ARTICLES) {
    try {
      await sql(
        `INSERT INTO articles (id, title_ar, slug, excerpt_ar, body_ar, category, seo_title, seo_description, published)
         VALUES (gen_random_uuid()::text, $1, $2, $3, $4, $5, $6, $7, true)
         ON CONFLICT (slug) DO UPDATE SET
           title_ar = $1, excerpt_ar = $3, body_ar = $4,
           category = $5, seo_title = $6, seo_description = $7, published = true`,
        [article.title_ar, article.slug, article.excerpt_ar, article.body_ar,
         article.category, article.seo_title, article.seo_description]
      )
      console.log('✅ ' + article.slug)
    } catch (e) {
      console.error('❌ ' + article.slug + ': ' + e.message)
    }
  }
  console.log('Done! 10 articles seeded.')
  process.exit(0)
}

